CREATE TABLE IF NOT EXISTS users (
  id INT PRIMARY KEY AUTO_INCREMENT,
  name VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS matchinfo (
  id INT PRIMARY KEY AUTO_INCREMENT,
  user1 INT,
  user2 INT,
  user1Hand VARCHAR(255),
  isActive BOOLEAN
);

CREATE TABLE IF NOT EXISTS matches (
  id INT PRIMARY KEY AUTO_INCREMENT,
  user1 INT,
  user2 INT,
  user1Hand VARCHAR(255),
  user2Hand VARCHAR(255),
  winner VARCHAR(255)
);
